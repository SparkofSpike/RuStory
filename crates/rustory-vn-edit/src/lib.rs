#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_operation_appears_once() {
        let names: Vec<&str> = catalogue().iter().map(|info| info.name).collect();
        let mut unique = names.clone();
        unique.sort_unstable();
        unique.dedup();
        assert_eq!(
            names.len(),
            unique.len(),
            "an operation is listed twice in the catalogue"
        );
    }

    #[test]
    fn every_example_parses_back_into_its_operation() {
        // The promise the example makes to an agent is "copy this and it works". A
        // hand-written example can break that promise silently; one generated from a
        // real value cannot, and this test proves the round trip holds anyway.
        for info in catalogue() {
            let value: serde_json::Value = serde_json::from_str(&info.example)
                .unwrap_or_else(|err| panic!("{}: {err}", info.name));
            assert_eq!(
                value["op"], info.name,
                "{} serialised under a different operation name",
                info.name
            );
            let _: EditOp = serde_json::from_str(&info.example)
                .unwrap_or_else(|err| panic!("{}: {err}", info.name));
        }
    }
}
