/// The shape of an operation as an agent sees it.
///
/// `rustory ops --json` prints one entry per operation so a caller can discover the
/// vocabulary instead of being told it out of band. Kept next to the enum so adding
/// an operation without documenting it is a compile error rather than a doc drift:
/// [`catalogue`] fails to build if a variant is unhandled.
#[derive(Debug, Clone, serde::Serialize)]
pub struct OpInfo {
    pub name: &'static str,
    pub summary: &'static str,
    pub changes_structure: bool,
    /// The operation as a JSON body that parses, so a caller can copy it instead of
    /// inferring field names from prose.
    ///
    /// Generated by serialising the sample rather than written by hand: an example
    /// that cannot drift from the schema it demonstrates is worth more than a prettier
    /// one that can.
    pub example: String,
}

/// Every operation, with a one-line description and a usable JSON example.
#[must_use]
pub fn catalogue() -> Vec<OpInfo> {
    use EditOp as E;

    // A match rather than a list, so a new variant forces this function to be
    // updated: `catalogue` will not compile otherwise.
    fn describe(op: &E) -> OpInfo {
        let (name, summary, changes_structure) = match op {
            E::SetTitle { .. } => ("SetTitle", "Set or clear the story title.", false),
            E::SetAuthor { .. } => ("SetAuthor", "Set or clear the story author.", false),
            E::SetStartNode { .. } => (
                "SetStartNode",
                "Choose which node the story begins at.",
                false,
            ),
            E::CreateNode { .. } => ("CreateNode", "Add an empty node that ends the story.", true),
            E::DeleteNode { .. } => (
                "DeleteNode",
                "Remove a node. Refused while anything still points at it.",
                true,
            ),
            E::RenameNode { .. } => (
                "RenameNode",
                "Rename a node and rewrite every reference to it.",
                true,
            ),
            E::DuplicateNode { .. } => (
                "DuplicateNode",
                "Copy a node's beats and exit under a new id.",
                true,
            ),
            E::InsertBeat { .. } => ("InsertBeat", "Insert a beat at an index in a node.", true),
            E::UpdateBeat { .. } => ("UpdateBeat", "Replace the beat at an index.", false),
            E::DeleteBeat { .. } => ("DeleteBeat", "Remove a beat at an index.", true),
            E::MoveBeat { .. } => ("MoveBeat", "Reorder beats within a node.", true),
            E::SetExit { .. } => (
                "SetExit",
                "Replace a node's exit (end, goto, choose or gameplay).",
                true,
            ),
            E::AddChoice { .. } => (
                "AddChoice",
                "Append an option to a node that offers choices.",
                true,
            ),
            E::UpdateChoice { .. } => (
                "UpdateChoice",
                "Change an option's label or destination.",
                false,
            ),
            E::DeleteChoice { .. } => (
                "DeleteChoice",
                "Remove an option from a node that offers choices.",
                true,
            ),
            E::MoveChoice { .. } => (
                "MoveChoice",
                "Reorder options. The order is the order the player reads.",
                true,
            ),
            E::SetOutcome { .. } => ("SetOutcome", "Map a gameplay outcome key to a node.", true),
            E::DeleteOutcome { .. } => {
                ("DeleteOutcome", "Remove a gameplay outcome mapping.", true)
            }
            E::SetGameplayConfig { .. } => (
                "SetGameplayConfig",
                "Replace the RON config a gameplay system receives.",
                false,
            ),
        };

        OpInfo {
            name,
            summary,
            changes_structure,
            example: serde_json::to_string(op).unwrap_or_default(),
        }
    }

    // One representative of each variant: it drives `describe` and becomes the example
    // callers copy, which is why the values read like a real story rather than `x`.
    let samples = [
        E::SetTitle {
            title: Some("A Story".into()),
        },
        E::SetAuthor {
            author: Some("An Author".into()),
        },
        E::SetStartNode {
            node: NodeId::from("prologue"),
        },
        E::CreateNode {
            id: NodeId::from("epilogue"),
            at: None,
        },
        E::DeleteNode {
            id: NodeId::from("epilogue"),
        },
        E::RenameNode {
            from: NodeId::from("prologue"),
            to: NodeId::from("opening"),
        },
        E::DuplicateNode {
            id: NodeId::from("prologue"),
            as_id: NodeId::from("prologue-copy"),
        },
        E::InsertBeat {
            node: NodeId::from("prologue"),
            index: 1,
            beat: Beat::Say {
                speaker: Some(ActorId::from("yuki")),
                text: "You haven't left yet?".into(),
            },
        },
        E::UpdateBeat {
            node: NodeId::from("prologue"),
            index: 1,
            beat: Beat::Say {
                speaker: Some(ActorId::from("yuki")),
                text: "You haven't left yet?".into(),
            },
        },
        E::DeleteBeat {
            node: NodeId::from("prologue"),
            index: 1,
        },
        E::MoveBeat {
            node: NodeId::from("prologue"),
            from: 0,
            to: 1,
        },
        E::SetExit {
            node: NodeId::from("prologue"),
            exit: Exit::Goto {
                to: NodeId::from("epilogue"),
            },
        },
        E::AddChoice {
            node: NodeId::from("prologue"),
            label: "Tell the truth".into(),
            to: NodeId::from("honest"),
        },
        E::UpdateChoice {
            node: NodeId::from("prologue"),
            index: 0,
            label: Some("Tell the truth".into()),
            to: Some(NodeId::from("honest")),
        },
        E::DeleteChoice {
            node: NodeId::from("prologue"),
            index: 0,
        },
        E::MoveChoice {
            node: NodeId::from("prologue"),
            from: 0,
            to: 1,
        },
        E::SetOutcome {
            node: NodeId::from("confession"),
            outcome: OutcomeKey::from("correct"),
            to: NodeId::from("honest"),
        },
        E::DeleteOutcome {
            node: NodeId::from("confession"),
            outcome: OutcomeKey::from("correct"),
        },
        E::SetGameplayConfig {
            node: NodeId::from("confession"),
            config: Some("(duration_ms: 3000, prompt: Some(\"She is waiting\"))".into()),
        },
    ];

    samples.iter().map(describe).collect()
}

